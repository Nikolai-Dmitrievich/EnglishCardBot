from src.db.db_session import database_exists, create_database, drop_database, init_db

if __name__ == "__main__":
    """
    Скрипт для управления базой данных проекта.

    При запуске проверяет, существует ли база данных.
    Если база отсутствует — создаёт новую.
    Если база существует — предлагает удалить и создать заново либо использовать существующую.

    Затем инициализирует структуру базы данных — создаёт необходимые таблицы.

    Использование:
        python -m src.db.create_db

    Ввод с консоли необходим только при наличии базы данных для подтверждения её удаления.
    """
    if not database_exists():
        print("База данных не найдена. Создаю новую...")
        create_database()
    else:
        answer = input("База данных существует. Хотите удалить её и создать заново? (y/N): ").strip().lower()
        if answer == 'y':
            drop_database()
            create_database()
        else:
            print("Используется существующая база данных.")

    print("Инициализирую таблицы...")
    init_db()
    print("База данных готова.")
